#!/usr/bin/env python3
"""
Builds db/seed/corrections-2026-10-23.sql (Phase 1.1, owner approval 23 Oct 2026 11:14 — development and preview only)
from data/official-records-corrections-2026-10-22.json, the one file where the corrections are written. Nothing in the
SQL is typed by hand: texts, amounts and evidence come from the JSON, so the database and the pages cannot drift apart.

  python3 scripts/build_corrections_2026_10_23.py   →  rewrites db/seed/corrections-2026-10-23.sql
"""
import json
from datetime import datetime, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parent.parent
FIX = json.loads((ROOT / "data/official-records-corrections-2026-10-22.json").read_text())
V2 = json.loads((ROOT / "data/official-records-2026-10-14.v2.json").read_text())
CHECKED_AT = "2026-10-23T12:00:00+03:00"
# requirement_key in the database for each rule category of the checked file (db/seed/official-records-2026-10-14.sql)
REQ_KEY = {
    "art5b": {"NEW:tax_residence_transfer": "tax_residence_transfer-1", "NEW:prior_tax_residence": "prior_tax_residence-2",
              "NEW:moving_from_country_group": "moving_from-3", "NEW:pension_income": "activity_in_greece-4"},
    "art5a": {"NEW:prior_tax_residence": "prior_tax_residence-1", "NEW:investment_amount": "investment_amount-2"},
}


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def j(o) -> str:
    return q(json.dumps(o, ensure_ascii=False)) + "::jsonb"


def next_deadline_utc(rule: dict, now: datetime) -> str:
    """Same arithmetic as src/lib/site/move-year.ts: the earliest application deadline still open for someone."""
    tz = ZoneInfo(rule["timezone"])
    y0 = now.astimezone(tz).year
    in_force = datetime.fromisoformat(rule["rules_in_force_from"] + "T00:00:00+00:00")
    found = []
    for y in (y0 - 1, y0):
        for a in (y, y + 1):
            m, d = map(int, rule["application_by"].split("-"))
            end = datetime(a, m, d, tzinfo=tz) + timedelta(days=1) - timedelta(seconds=1)
            if end >= in_force and end >= now:
                found.append(end)
    return min(found).astimezone(ZoneInfo("UTC")).strftime("%Y-%m-%dT%H:%M:%SZ")


def main() -> None:
    now = datetime.fromisoformat(CHECKED_AT)
    R = FIX["records"]
    B = FIX["business_records"]
    base = {r["id"]: r for r in V2["records"]}
    out = [
        "-- GENERATED by scripts/build_corrections_2026_10_23.py from data/official-records-corrections-2026-10-22.json — do not edit by hand.",
        "-- Phase 1.1 (owner approval, Lydia, 23 Oct 2026 11:14; development database / preview only). Run after corrections-2026-10-22.sql.",
        "-- 5Β: summary without the unconfirmed start year; 5Α and 5Β: deadline wording without a date for everyone (the pages compute",
        "-- the deadlines by year of move from the same file); evidence of the eligibility rules → the 2026 decisions (rules unchanged);",
        "-- ΔΑΜ22 / ΔΑΜ23: the budget term of the official call. Earlier state kept in opportunity_versions. Idempotent.",
        "BEGIN;",
        "",
        "CREATE TEMP TABLE fix (key text PRIMARY KEY, summary text NOT NULL) ON COMMIT DROP;",
        "INSERT INTO fix VALUES",
    ]
    summaries = {
        "manual:art5b": "Διόρθωση 23/10/2026: σύνοψη «15 φορολογικά έτη συνολικά» (Α.1192/2026, άρθρο 4 παρ. 3)· προθεσμίες ανά έτος μεταφοράς (άρθρο 4 παρ. 1)",
        "manual:art5a": "Διόρθωση 23/10/2026: προθεσμίες ανά έτος μεταφοράς, χωριστά αίτηση και δικαιολογητικά (Α.1147/2026, άρθρο 4 παρ. 1 και 4)",
    }
    for k, b in B.items():
        summaries[k] = f"Διόρθωση 23/10/2026 ({b['label']}): «{b['official_wording']}» — {b['source']['label']}"
    out.append(",\n".join(f"  ({q(k)}, {q(v)})" for k, v in summaries.items()) + ";")
    out += [
        "",
        "INSERT INTO opportunity_versions (opportunity_id, version, snapshot, change_kind, change_summary)",
        "SELECT o.id, o.version, to_jsonb(o.*) - 'version', 'admin_correction', f.summary",
        "FROM opportunities o JOIN fix f ON f.key = o.external_key",
        "WHERE o.merged_into_id IS NULL",
        "  AND NOT EXISTS (SELECT 1 FROM opportunity_versions v WHERE v.opportunity_id = o.id AND v.change_summary = f.summary)",
        "ON CONFLICT (opportunity_id, version) DO NOTHING;",
        "",
    ]
    for rid in ("art5b", "art5a"):
        f = R[rid]
        key = f"manual:{rid}"
        summary = (f.get("summary") or base[rid]["summary"])["el"]
        benefit = base[rid]["funding_or_benefit"]["value"]["el"]
        rule = f["deadline_rule"]
        sets = [
            f"summary_plain = {q(summary + ' Ποσό / όφελος: ' + benefit)}",
            f"deadline_original_text = {q(f['application_status']['deadline_original_wording']['el'])}",
            f"closes_at = {q(next_deadline_utc(rule, now))}",
            f"status_evidence = status_evidence || {j({'rechecked_at': CHECKED_AT, 'deadline_rule': 'by_year_of_move', 'governing_document': rule['basis']['el']})}",
            f"last_retrieved_at = {q(CHECKED_AT)}, last_verified_at = {q(CHECKED_AT)}",
            "version = version + 1, updated_at = now()",
        ]
        out.append(f"-- {key}")
        out.append("UPDATE opportunities SET\n  " + ",\n  ".join(sets))
        out.append(f"WHERE external_key = {q(key)} AND merged_into_id IS NULL AND last_verified_at IS DISTINCT FROM {q(CHECKED_AT)};")
        for cat, ev in f.get("eligibility_evidence", {}).items():
            e = {"source_url": ev["source_url"], "checked_on": "2026-10-23"}
            if ev.get("location"):
                e["location"] = ev["location"]
            if ev.get("excerpt"):
                e["excerpt"] = ev["excerpt"]
            out.append(f"UPDATE opportunity_requirements SET evidence = {j(e)}")
            out.append(f"WHERE requirement_key = {q(REQ_KEY[rid][cat])} AND superseded_at IS NULL")
            out.append(f"  AND opportunity_id = (SELECT id FROM opportunities WHERE external_key = {q(key)} AND merged_into_id IS NULL);")
        out.append("")
    for k, b in B.items():
        pb = b["project_budget"]
        out.append(f"-- {b['label']}: {b['official_wording']}")
        out.append("UPDATE opportunities SET")
        out.append(f"  official_details = jsonb_set(official_details, '{{funding,project_budget}}', {j(pb)}),")
        out.append(f"  summary_plain = {q(b['summary_plain'])},")
        out.append(f"  status_evidence = status_evidence || {j({'rechecked_at': CHECKED_AT, 'recheck': b['source']['label'] + ': «' + b['official_wording'] + '»', 'source': b['source']['url']})},")
        out.append(f"  last_retrieved_at = {q(CHECKED_AT)}, last_verified_at = {q(CHECKED_AT)},")
        out.append("  version = version + 1, updated_at = now()")
        out.append(f"WHERE external_key = {q(k)} AND merged_into_id IS NULL AND last_verified_at IS DISTINCT FROM {q(CHECKED_AT)};")
        out.append("")
    out += [
        "INSERT INTO audit_logs (actor_user_id, action, entity_type, entity_id, details)",
        "SELECT NULL, 'opportunity_corrected', 'opportunity', o.id::text,",
        "       jsonb_build_object('external_key', o.external_key, 'summary', f.summary, 'approved_by', 'owner', 'approved_on', '2026-10-23T11:14:00+03:00',",
        "                          'scope', 'preview_only', 'via', 'db/seed/corrections-2026-10-23.sql')",
        "FROM opportunities o JOIN fix f ON f.key = o.external_key",
        "WHERE o.merged_into_id IS NULL",
        "  AND NOT EXISTS (SELECT 1 FROM audit_logs a WHERE a.entity_id = o.id::text AND a.action = 'opportunity_corrected' AND a.details->>'summary' = f.summary);",
        "",
        "COMMIT;",
        "",
    ]
    (ROOT / "db/seed/corrections-2026-10-23.sql").write_text("\n".join(out))


if __name__ == "__main__":
    main()
