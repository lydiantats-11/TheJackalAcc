#!/usr/bin/env python3
"""
Builds db/seed/business-records-2026-10-20.sql and db/seed/approvals-2026-10-20.sql from
data/business-records-2026-10-20.json (11 business calls checked by hand in their official call documents on
20 Oct 2026; approved by the owner the same day for the development database / preview only).

Imported as publication_basis = 'manual_review', requirement_set_completeness = 'partial'. Only the applicant type is
stored as a requirement (used to sort and label listings); every other condition stays in the summary and the
uncertainties until a reviewed rule list exists. No categories are linked: the taxonomy is pending the owner's
confirmation. Re-runnable: deletes and re-inserts only these external keys.
"""
import json
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "business-records-2026-10-20.json"
OUT = ROOT / "db" / "seed" / "business-records-2026-10-20.sql"
APPROVALS = ROOT / "db" / "seed" / "approvals-2026-10-20.sql"
HOST_SOURCE = {"opske.gr": "opske", "efepae.gr": "efepae"}


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (dict, list)):
        return "'" + json.dumps(v, ensure_ascii=False).replace("'", "''") + "'::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    at = data["checked_at"]
    recs = data["records"]
    keys = [r["external_key"] for r in recs]
    if len(set(keys)) != len(keys):
        raise SystemExit("duplicate external_key")
    if len({r["canonical_url"] for r in recs}) != len(recs):
        raise SystemExit("duplicate canonical_url")
    out = ["-- GENERATED by scripts/build_business_seed.py — do not edit by hand.",
           f"-- Source: {SRC.name} ({data['schema_version']}), checked {at} by manual review of official call documents.",
           "-- Imported as review_status = 'pending'; db/seed/approvals-2026-10-20.sql records the owner's approval (preview only).",
           "BEGIN;",
           "DELETE FROM opportunities WHERE external_key IN (" + ", ".join(q(k) for k in keys) + ") AND publication_basis = 'manual_review';"]
    for r in recs:
        host = urlparse(r["canonical_url"]).hostname
        src = HOST_SOURCE[host]
        evidence = {"checked_at": at, "method": "manual review of the official call document and its latest amendment",
                    "governing_document": r["governing_document"], "sources": [r["canonical_url"]] + [d[1] for d in r["documents"]],
                    "status_as_checked": "open", "approved_by_owner_on": "2026-10-20"}
        details = {"source": "manual-review",
                   "call": {"identifier": r["official_identifier"], "title": None},
                   "documents": [{"label": d[0], "url": d[1]} for d in r["documents"]]}
        details["funding"] = r["funding"]
        if r.get("total_budget"):
            details["budget"] = {"total_eur": r["total_budget"], "by_year": {}, "expected_grants": None, "min_grant_eur": None, "max_grant_eur": None}
        cols = {
            "is_synthetic": False, "source_id": f"__SRC__{src}", "official_identifier": r["official_identifier"],
            "official_title": r["title"], "title_lang": "el", "summary_plain": r["summary"], "summary_origin": "admin",
            "opportunity_type": r["type"], "publishing_authority": r["authority"], "canonical_url": r["canonical_url"],
            "application_url": r["application_url"], "opens_at": r["opens_at"], "closes_at": r["closes_at"],
            "deadline_state": "known", "deadline_kind": "official", "deadline_is_date_only": False, "deadline_timezone": "Europe/Athens",
            "deadline_original_text": r["deadline_verbatim"], "last_retrieved_at": at, "last_verified_at": at,
            "status": "open", "status_confidence": "high", "status_evidence": evidence, "status_reason": "manual_review_2026_10_20",
            "review_status": "pending", "publication_basis": "manual_review", "external_key": r["external_key"], "record_kind": "call",
            "stale_after_days": 7, "uncertainties": r["uncertainties"], "requirement_set_completeness": "partial", "has_conflict": False,
            "funding_intensity_pct": None, "official_details": details,
        }
        vals = []
        for k, v in cols.items():
            vals.append(f"(SELECT id FROM sources WHERE slug = {q(v[7:])})" if isinstance(v, str) and v.startswith("__SRC__") else q(v))
        out.append(f"\n-- {r['id']}: {r['official_identifier']} · closes {r['closes_at']}")
        out.append(f"WITH o AS (INSERT INTO opportunities ({', '.join(cols)}) VALUES ({', '.join(vals)}) RETURNING id)")
        # The applicant text is a platform summary: no excerpt, so it is never shown as an official quotation.
        ev = {"source_url": r["documents"][0][1], "location": "σύνοψη της πλατφόρμας από το έγγραφο"}
        out.append("INSERT INTO opportunity_requirements (opportunity_id, requirement_key, category, kind, value, original_text, original_lang, "
                   "interpretation, evidence, evidence_rank, confidence, flags, origin, verified_at)\nVALUES ((SELECT id FROM o), 'applicant_type-1', "
                   f"'applicant_type', 'mandatory', {q({'types': r['applicants']})}, {q(r['applicant_text'])}, 'el', NULL, {q(ev)}, 2, 'medium', "
                   f"'{{}}'::text[], 'manual_review', {q(at)});")
    out.append("\nCOMMIT;")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")

    ap = ["-- Owner approval (Lydia, Claude session of 20 Oct 2026): import the reviewed business batch into the development",
          "-- database / preview only — not public. Run after business-records-2026-10-20.sql. Idempotent.",
          "BEGIN;",
          "WITH approved AS (",
          "  UPDATE opportunities SET review_status = 'approved', updated_at = now()",
          "  WHERE external_key IN (" + ", ".join(q(k) for k in keys) + ")",
          "    AND publication_basis = 'manual_review' AND review_status = 'pending' AND merged_into_id IS NULL",
          "  RETURNING id, external_key",
          "), reviews AS (",
          "  INSERT INTO admin_reviews (opportunity_id, reviewer_id, decision, notes)",
          "  SELECT id, NULL, 'approved', 'Approved by the owner (Lydia) in the Claude session of 20 Oct 2026 for the development database / preview only, after the final check of the latest amendments on 20 Oct 2026.' FROM approved",
          ")",
          "INSERT INTO audit_logs (actor_user_id, action, entity_type, entity_id, details)",
          "SELECT NULL, 'opportunity_approved', 'opportunity', id::text,",
          "       jsonb_build_object('external_key', external_key, 'approved_by', 'owner', 'approved_on', '2026-10-20', 'scope', 'preview_only', 'via', 'db/seed/approvals-2026-10-20.sql')",
          "FROM approved;",
          "COMMIT;"]
    APPROVALS.write_text("\n".join(ap) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(recs)} records) and {APPROVALS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
